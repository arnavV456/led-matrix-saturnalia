import sys
from PIL import Image
import numpy as np
src, out = sys.argv[1], sys.argv[2]
G = float(sys.argv[3]) if len(sys.argv) > 3 else 2.2   # gain: thin strokes need boosting
im = Image.open(src).convert("RGB")
a = np.asarray(im).astype(float)
# blue-ness mask (logo only; text is black so excluded)
mask = ((a[...,2] - a[...,0]) > 60)
ys, xs = np.where(mask)
x0, x1, y0, y1 = xs.min(), xs.max()+1, ys.min(), ys.max()+1
cov = mask[y0:y1, x0:x1].astype(float)
h, w = cov.shape
S = 16
scale = S / max(w, h)
nw, nh = max(1, round(w*scale)), max(1, round(h*scale))
small = np.asarray(Image.fromarray((cov*255).astype('uint8')).resize((nw*8, nh*8), Image.LANCZOS)).astype(float)/255
# box average down to nw x nh
small = small[:nh*8,:nw*8].reshape(nh,8,nw,8).mean(axis=(1,3))
v = np.clip(small*G, 0, 1)
canvas = np.zeros((S,S)); ox, oy = (S-nw)//2, (S-nh)//2
canvas[oy:oy+nh, ox:ox+nw] = v
for r in canvas: print("".join(" .:*#"[min(4,int(x*4.99))] for x in r))
BLUE = np.array([0, 72, 186]) / 255.0
with open(out, "w") as f:
    f.write("// Auto-generated by tools/logo2h.py - 16x16 RGB, row-major\n#pragma once\n#include <stdint.h>\n")
    f.write("const uint8_t LOGO[16*16][3] = {\n")
    for y in range(S):
        f.write("  " + ", ".join("{%d,%d,%d}" % tuple(int(round(c*canvas[y,x]*255)) for c in BLUE) for x in range(S)) + ",\n")
    f.write("};\n")
